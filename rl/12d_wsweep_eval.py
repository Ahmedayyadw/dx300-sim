"""Lab 12d: energy-weight sweep of residual SAC on the real plant. No training.

Evaluates rl/models/12_residual_w{w}_s{0,1,2}.zip for w in W_LIST with exactly the Lab 12
protocol (rl/12_eval.py: 100 unseen scenarios x 72 rows, 10 substeps, same rollout code), so
the result answers whether any energy weight lets residual SAC beat the Lab 11 PID points.
rl/12_eval.py is imported and used unchanged; only its model table is replaced here.

Usage (repo root, .venv active):
  python rl/12d_wsweep_eval.py           evaluate (about 15-20 min on 16 cores) + report
  python rl/12d_wsweep_eval.py --report  report only, from rl/12d_wsweep.csv
Writes rl/12d_wsweep.csv, rl/12d_wsweep.md, rl/12d_wsweep.png.
Check: the w = 0.1 rows must equal the sac_residual rows of rl/12_eval.csv.
"""

import collections
import importlib.util
import math
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
_spec = importlib.util.spec_from_file_location("lab12_eval", os.path.join(HERE, "12_eval.py"))
M = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(M)

W_LIST = (0.0, 0.01, 0.03, 0.1, 0.3, 1.0)
OUT_CSV = "rl/12d_wsweep.csv"
MD_PATH = "rl/12d_wsweep.md"
PNG_PATH = "rl/12d_wsweep.png"
REF_CSV = "rl/12_eval.csv"  # read only (PID points, w = 0.1 check)
KEYS = ("share_over_20cm", "mean_E_mech_kJ", "mean_t_reach_s", "n_never_reached")


def label(w):
    return f"res_w{w}"


# replace the model table of rl/12_eval.py (runs again in every spawned worker)
M.SAC_MODELS = {label(w): ("12", "residual", "residual") for w in W_LIST}
_W_OF = {label(w): w for w in W_LIST}
M.model_path = lambda lab, seed: f"{M.MODEL_DIR}/12_residual_w{_W_OF[lab]}_s{seed}.zip"


def run(job):
    return M.run_row(job)


def jobs():
    return [
        (lab, "sac", (lab, s), s, M.SET, g, n, c, v)
        for lab in M.SAC_MODELS
        for s in M.SEEDS
        for g, n, c, v in M.ROWS72
    ]


def summarise(rows):
    """Per controller: seed means over the 72 rows, then mean (and range) over seeds."""
    by = collections.defaultdict(list)
    for r in rows:
        by[(r["controller"], r["sac_seed"])].append(r)
    out = collections.defaultdict(list)
    for (ctrl, seed), rs in by.items():
        miss = np.array([float(r["share_over_20cm"]) for r in rs]) * 100
        e = float(np.mean([float(r["mean_E_mech_kJ"]) for r in rs]))
        floor = float(np.mean([float(r["mean_floor_kJ"]) for r in rs]))
        out[ctrl].append(
            {
                "miss": float(miss.mean()),
                "broken": int((miss > 5).sum()),
                "degraded": int(((miss >= 1) & (miss <= 5)).sum()),
                "E": e,
                "gap": 100 * (e / floor - 1),
                "reach": float(np.nanmean([float(r["mean_t_reach_s"]) for r in rs])),
                "never": int(sum(int(r["n_never_reached"]) for r in rs)),
            }
        )
    return out


def check_w01(rows):
    """The w = 0.1 rows must reproduce rl/12_eval.csv (sac_residual) exactly."""
    if not os.path.exists(REF_CSV):
        return "check skipped: rl/12_eval.csv missing"
    ref = {
        (int(float(r["sac_seed"])), r["condition"], r["variant"]): r
        for r in M.L11.read_csv(REF_CSV)
        if r["controller"] == "sac_residual"
    }
    worst, n = 0.0, 0
    for r in rows:
        if r["controller"] != label(0.1):
            continue
        q = ref[(int(float(r["sac_seed"])), r["condition"], r["variant"])]
        for k in KEYS:
            a, b = float(r[k]), float(q[k])
            if not (math.isnan(a) and math.isnan(b)):
                worst = max(worst, abs(a - b))
        n += 1
    return (
        f"check: w = 0.1 equals rl/12_eval.csv sac_residual on {n} rows,"
        f" largest difference {worst:.3g}"
    )


def report(rows, check_line=""):
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    s = summarise(rows)
    pid = (
        summarise([r for r in M.L11.read_csv(REF_CSV) if r["controller"] in M.ROLES])
        if os.path.exists(REF_CSV)
        else {}
    )
    lines = [
        "# Lab 12d: energy-weight sweep of residual SAC on the real plant",
        "",
        "Generated by `python rl/12d_wsweep_eval.py`. No training. Lab 12 protocol: 100 unseen",
        "scenarios x 72 rows, 10 substeps. SAC: mean over 3 seeds of the per-seed means; range in",
        "brackets. Rows broken (over 5 % misses) / degraded (1-5 %) are counted per seed and",
        "averaged; rl/12_eval.md counts them on the seed-mean miss rate instead.",
        "All values ESTIMATED.",
        "",
    ]
    if check_line:
        lines += [check_line, ""]
    lines += [
        "| controller | miss % | rows broken / degraded | E_mech kJ | gap to floor %"
        " | reach 20 cm s | never reached |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]

    def line(name, v):
        m = [x["miss"] for x in v]
        rng = f" ({min(m):.2f}-{max(m):.2f})" if len(v) > 1 else ""
        return (
            f"| {name} | {np.mean(m):.2f}{rng} | {np.mean([x['broken'] for x in v]):.1f} / "
            f"{np.mean([x['degraded'] for x in v]):.1f} | {np.mean([x['E'] for x in v]):.1f} | "
            f"{np.mean([x['gap'] for x in v]):.1f} | {np.mean([x['reach'] for x in v]):.2f} | "
            f"{sum(x['never'] for x in v)} |"
        )

    for role in M.ROLES:
        if role in pid:
            lines.append(line(f"{role} PID + fix 2b", pid[role]))
    for w in W_LIST:
        if label(w) in s:
            lines.append(line(f"residual SAC, w = {w:g}", s[label(w)]))
    lines += ["", f"![energy vs misses]({os.path.basename(PNG_PATH)})", ""]
    with open(MD_PATH, "w") as f:
        f.write("\n".join(lines) + "\n")

    fig, ax = plt.subplots(figsize=(5.2, 3.6))
    for role in M.ROLES:
        if role in pid:
            v = pid[role][0]
            ax.scatter(v["E"], v["miss"], marker="s", s=50, color="#1f5fa8")
            ax.annotate(
                f"PID {role}",
                (v["E"], v["miss"]),
                textcoords="offset points",
                xytext=(5, 4),
                fontsize=8,
            )
    pts = [
        (np.mean([x["E"] for x in s[label(w)]]), np.mean([x["miss"] for x in s[label(w)]]), w)
        for w in W_LIST
        if label(w) in s
    ]
    if pts:
        ax.plot(
            [p[0] for p in pts], [p[1] for p in pts], "o-", color="#d9822b", label="residual SAC"
        )
        for e, m, w in pts:
            ax.annotate(f"w={w:g}", (e, m), textcoords="offset points", xytext=(5, -10), fontsize=8)
    ax.set_xlabel("mean mechanical energy per move [kJ]")
    ax.set_ylabel("moves over 20 cm [%]")
    ax.grid(alpha=0.3)
    ax.legend(loc="best", fontsize=8)
    fig.tight_layout()
    fig.savefig(PNG_PATH, dpi=150)
    print("\n".join(lines))


def smoke():
    """2 labels x 2 rows with a = 0 (no models needed): must equal the balanced PID rows."""
    js = [
        (lab, "sac", (lab, None), None, "orig20", g, n, c, v)
        for lab in list(M.SAC_MODELS)[:2]
        for g, n, c, v in M.ROWS72[:2]
    ]
    rows = M.pool_map(run, js)
    pid = M.pool_map(run_pid, [(g, n, c, v) for g, n, c, v in M.ROWS72[:2]])
    worst = max(
        abs(r[k] - p[k]) for r, p in zip(rows, pid * 2) for k in ("mean_deg", "mean_E_mech_kJ")
    )
    print(
        f"smoke: {len(rows)} rows through the pool,"
        f" a = 0 vs balanced PID largest difference {worst}"
    )
    print("model files:", M.model_path(label(0.0), 0), M.model_path(label(1.0), 2))


def run_pid(row):
    g, n, c, v = row
    return M.run_row(("balanced", "pid", M.E.BAL_GAINS, None, "orig20", g, n, c, v))


def main():
    if "--smoke" in sys.argv:
        smoke()
        return
    if "--report" in sys.argv:
        report(M.L11.read_csv(OUT_CSV))
        return
    missing = [
        M.model_path(lab, s)
        for lab in M.SAC_MODELS
        for s in M.SEEDS
        if not os.path.exists(M.model_path(lab, s))
    ]
    if missing:
        sys.exit("missing models (train them first):\n  " + "\n  ".join(missing))
    rows = M.pool_map(run, jobs())
    M.L11.write_csv(OUT_CSV, rows)
    report(M.L11.read_csv(OUT_CSV), check_w01(M.L11.read_csv(OUT_CSV)))


if __name__ == "__main__":
    main()
