"""Lab 12f: boom cylinder loads per controller on the real plant. Study, not in the paper.
No training.

Same controllers, rows and rollouts as rl/12e_stats_eval.py (imported, unchanged); the only
addition is a recorder on env.step that keeps, for every 50 ms control step, the boom angle after
the step and the mean cylinder torque of the step (info["tau_cyl"]). From these, per move:

  F_peak_kN      largest |F| of the two boom cylinders together, F = tau_cyl / r(theta)
  p_peak_bar     largest cylinder pressure, F / A_cap when pushing (F > 0), |F| / A_ann when
                 pulling (no back pressure; the plant's torque limit is the 330 bar relief,
                 OFFICIAL)
  dFdt_peak_kNs  largest |dF/dt| between control steps: how sharply the load changes (shock on
                 pins/seals)
  F_travel_kN    sum of |dF| over the move: total load variation, a simple fatigue/wear proxy
  F_turns        number of turning points of F (local max/min): load oscillations per move
  at_relief      share of steps at >= 99 % of the relief pressure

All values are 50 ms step averages of the rigid Python plant (no oil compressibility, no valve
dynamics), so real pressure peaks are higher; the numbers compare controllers with each other,
they are not design loads. All values ESTIMATED.

Usage (repo root, .venv active):
  python rl/12f_cylinder_loads.py            evaluate (about 20-25 min on 16 cores) + report
  python rl/12f_cylinder_loads.py --report   report only, from rl/12f_loads.csv.gz
  python rl/12f_cylinder_loads.py --smoke    2 rows of the tuning set, PID only, no models needed
Writes rl/12f_loads.csv.gz and rl/12f_loads.md.
"""

import collections
import csv
import gzip
import importlib.util
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
_spec = importlib.util.spec_from_file_location("lab12e", os.path.join(HERE, "12e_stats_eval.py"))
X = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(X)
M, E, L10, L11 = X.M, X.E, X.L10, X.L11
R = L10.R

OUT = "rl/12f_loads.csv.gz"
MD_PATH = "rl/12f_loads.md"
P_RELIEF_BAR = R.P_RELIEF_PA / 1e5
FIELDS = (
    "controller",
    "seed",
    "condition",
    "variant",
    "scen",
    "F_peak_kN",
    "p_peak_bar",
    "dFdt_peak_kNs",
    "F_travel_kN",
    "F_turns",
    "at_relief",
)


def loads(rec, dt):
    """Per-move load metrics from [(theta, tau_cyl), ...] of one move."""
    th = np.array([r[0] for r in rec])
    tau = np.array([r[1] for r in rec])
    F = tau / np.array([R.moment_arm(t) for t in th])  # N, both cylinders
    p = np.where(F >= 0, F / R.A_CAP_M2, -F / R.A_ANN_M2) / 1e5  # bar
    dF = np.diff(F)
    turns = int(np.sum(np.diff(np.sign(dF[np.abs(dF) > 1.0])) != 0)) if len(dF) > 2 else 0
    return {
        "F_peak_kN": float(np.abs(F).max() / 1e3),
        "p_peak_bar": float(p.max()),
        "dFdt_peak_kNs": float(np.abs(dF).max() / dt / 1e3) if len(dF) else 0.0,
        "F_travel_kN": float(np.abs(dF).sum() / 1e3),
        "F_turns": turns,
        "at_relief": float(np.mean(p >= 0.99 * P_RELIEF_BAR)),
    }


def run_row(job):
    """One controller (and seed) on one row: per-move load metrics. Worker."""
    label, seed, set_name, name, cond, variant = job
    env = L10.make_env(variant, **cond)
    rec = []
    step = env.step

    def recorded_step(action):  # same result, plus a record
        out = step(action)
        rec.append((env.th, out[4]["tau_cyl"]))
        return out

    env.step = recorded_step
    ctrl = X.make_ctrl(label, seed, cond.get("tau_noise", 0.0))
    out = []
    for i, sc in enumerate(L11.scenarios(set_name)):
        rec.clear()
        L11.rollout(ctrl, env, *sc)
        out.append(
            {
                "controller": label,
                "seed": "" if seed is None else seed,
                "condition": name,
                "variant": variant,
                "scen": i,
                **loads(rec, env.dt),
            }
        )
    return out


def report(rows):
    by = collections.defaultdict(lambda: collections.defaultdict(list))
    for r in rows:
        by[r["controller"]][r["seed"]].append(r)
    order = [c for c in list(X.PIDS) + list(X.SAC) if c in by]

    def ms(vals, f):
        v = np.asarray(vals, float)
        return f.format(v.mean()) + (" +- " + f.format(v.std(ddof=1)) if len(v) > 1 else "")

    def col(c, key, agg, f):
        return ms([agg(np.array([float(r[key]) for r in rs])) for rs in by[c].values()], f)

    lines = [
        "# Lab 12f: boom cylinder loads per controller (real plant)",
        "",
        "Generated by `python rl/12f_cylinder_loads.py`. Study, not in the paper. No training.",
        "Lab 12 protocol: 100 unseen scenarios x 72 rows per controller and seed. Values per move,",
        "then mean +- std over seeds. 50 ms step averages of the rigid plant: compare controllers,",
        f"not design loads. Relief pressure {P_RELIEF_BAR:.0f} bar. All values ESTIMATED.",
        "",
        "| controller | mean peak force kN | p95 peak force kN | max pressure bar"
        " | steps at relief % | mean peak dF/dt kN/s | p95 peak dF/dt kN/s"
        " | mean load travel kN | mean load turns |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for c in order:
        lines.append(
            f"| {c} | {col(c, 'F_peak_kN', np.mean, '{:.0f}')} | "
            f"{col(c, 'F_peak_kN', lambda a: np.percentile(a, 95), '{:.0f}')} | "
            f"{col(c, 'p_peak_bar', np.max, '{:.0f}')} | "
            f"{col(c, 'at_relief', lambda a: 100 * a.mean(), '{:.2f}')} | "
            f"{col(c, 'dFdt_peak_kNs', np.mean, '{:.0f}')} | "
            f"{col(c, 'dFdt_peak_kNs', lambda a: np.percentile(a, 95), '{:.0f}')} | "
            f"{col(c, 'F_travel_kN', np.mean, '{:.0f}')} | {col(c, 'F_turns', np.mean, '{:.1f}')} |"
        )
    lines += [
        "",
        "Reading guide: a smoother controller has lower peak dF/dt, less load travel and fewer",
        "load turns at a similar peak force; those load pins, bushings and seals less.",
    ]
    with open(MD_PATH, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


def write(rows):
    with gzip.open(OUT, "wt", newline="") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS)
        w.writeheader()
        w.writerows(rows)


def read():
    with gzip.open(OUT, "rt") as f:
        return list(csv.DictReader(f))


def smoke():
    """PID only, 2 rows of the tuning set: the recorder must leave every rollout unchanged."""
    _, n, c, v = M.ROWS72[0]
    gains = E.point_gains("economical")
    same = True
    for sc in L10.SCEN["orig20"][:3]:
        plain = L11.rollout(L11.Sched11(gains, E.EST), L10.make_env(v, **c), *sc)
        env, rec = L10.make_env(v, **c), []
        step = env.step

        def recorded_step(action, step=step, env=env, rec=rec):
            out = step(action)
            rec.append((env.th, out[4]["tau_cyl"]))
            return out

        env.step = recorded_step
        traced = L11.rollout(L11.Sched11(gains, E.EST), env, *sc)
        same &= plain["E_mech_kJ"] == traced["E_mech_kJ"] and plain["err_deg"] == traced["err_deg"]
    print("smoke: recorder leaves rollouts unchanged:", same)
    js = [(p, None, "orig20", n, c, v) for p in X.PIDS for _, n, c, v in M.ROWS72[:2]]
    rows = [m for chunk in M.pool_map(run_row, js) for m in chunk]
    r0 = rows[0]
    print(
        f"{len(rows)} moves through the pool; first: F_peak {r0['F_peak_kN']:.0f} kN,"
        f" p_peak {r0['p_peak_bar']:.0f} bar, dF/dt peak {r0['dFdt_peak_kNs']:.0f} kN/s,"
        f" turns {r0['F_turns']}"
    )


def main():
    if "--smoke" in sys.argv:
        smoke()
        return
    if "--report" in sys.argv:
        report(read())
        return
    missing = [
        X.model_path(lab, s)
        for lab in X.SAC
        for s in M.SEEDS
        if not os.path.exists(X.model_path(lab, s))
    ]
    if missing:
        sys.exit("missing models:\n  " + "\n  ".join(missing))
    rows = [m for chunk in M.pool_map(run_row, X.jobs()) for m in chunk]
    write(rows)
    report(read())


if __name__ == "__main__":
    main()
